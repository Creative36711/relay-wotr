// Пределы на роль и на карточку.
//
// Владелец сформулировал правило дословно: «если координатор сделал три
// карточки для Integration Auditor, наверное будет неправильно, если он
// разошлёт сразу все три карточки разным агентам Integration Auditor из разных
// контейнеров». Согласились на том, что это ограничивает транспорт, а не
// уговаривает промпт. Вот почему.
//
// Промпт — это просьба. Модель может её не выполнить: перепутать формулировку,
// не увидеть строку в длинном контексте, решить, что «на этот раз случай
// особый». Цена ошибки — два агента правят один файл, получаются две ветки,
// конфликт слияния и час разбирательств. Транспорт же отказывает
// детерминированно: одна и та же очередь плюс одно и то же состояние дают один
// и тот же ответ, и это проверяется тестом.
//
// Поэтому здесь два независимых запрета:
//
//   1. **На роль.** Пока у роли есть живая выдача, вторая не выдаётся — в
//      любой слот. Разные агенты одной роли делят оракул и файлы, и «параллельно
//      быстрее» здесь означает «параллельно дороже».
//   2. **На карточку.** Одна карточка — одна выдача. Это защита от дубля строки
//      в очереди: строку мог создать и человек, и повторный импорт, и ошибка
//      нарезки; выдавать её дважды нельзя ни при каком лимите.
//
// Обе причины отказа возвращаются текстом, который попадает в журнал и в
// ответ Координатору. Отказ без причины выглядит как зависание: агент не
// пришёл, карточка не двинулась, и никто не понимает почему.

import { norm } from "./util.mjs";

/** Статусы выдачи, при которых работа считается идущей. */
const LIVE = new Set(["issued", "alive"]);

export const isLiveRun = (run) => LIVE.has(norm(run?.["Статус"]));

/**
 * Сколько живых выдач у роли.
 *
 * Сравнение по нормализованному имени, а не по id: строку очереди и выдачу
 * заполняет то Координатор, то транспорт, и id роли в них может не быть —
 * имя есть всегда.
 */
export function liveRunsOfRole(runs = [], role = "") {
  const key = norm(role);
  if (!key) return [];
  return runs.filter((run) => isLiveRun(run) && norm(run["Роль"]) === key);
}

/** Живые выдачи по конкретной карточке: для запрета двойной выдачи. */
export function liveRunsOfCard(runs = [], card = "") {
  const key = norm(card);
  if (!key) return [];
  return runs.filter((run) => isLiveRun(run) && norm(run["Карточка"]) === key);
}

/**
 * Проверка пределов перед выдачей.
 *
 * Возвращает `{ ok, why, kind }`, где `kind` — машинный код причины. Он нужен,
 * чтобы пульт и журнал могли отличать «роль занята» от «карточка уже выдана»,
 * не разбирая текст.
 *
 * `maxPerRole` — предел на роль. По умолчанию 1: параллельность по умолчанию
 * выключена, потому что именно она даёт конфликт файлов. Поднимать её имеет
 * право человек, и только осознанно.
 */
export function roleLimits({
  role = "",
  card = "",
  runs = [],
  queue = [],
  maxPerRole = 1,
  ignoreRunId = "",
} = {}) {
  const live = runs.filter((run) => !ignoreRunId || norm(run["Run ID"]) !== norm(ignoreRunId));

  if (card) {
    const sameCard = liveRunsOfCard(live, card);
    if (sameCard.length) {
      const slot = sameCard[0]["Слот"] || "неизвестный слот";
      return {
        ok: false,
        kind: "card-busy",
        why: `карточка ${card} уже выдана (слот ${slot}) — вторая выдача той же карточки запрещена`,
        runs: sameCard,
      };
    }
  }

  if (role) {
    const sameRole = liveRunsOfRole(live, role);
    const limit = Number(maxPerRole);
    const effective = Number.isFinite(limit) && limit >= 1 ? limit : 1;
    if (sameRole.length >= effective) {
      const where = sameRole.map((run) => `${run["Слот"] || "?"}${run["Карточка"] ? ` (${run["Карточка"]})` : ""}`).join(", ");
      return {
        ok: false,
        kind: "role-busy",
        why:
          effective === 1
            ? `у роли «${role}» уже идёт работа: ${where}. Второй экземпляр этой роли не выдаётся — агенты одной роли делят файлы и оракул`
            : `у роли «${role}» ${sameRole.length} работ из ${effective}: ${where}`,
        runs: sameRole,
        limit: effective,
      };
    }
  }

  return { ok: true, why: "", runs: [] };
}

/**
 * Предупреждения для технического промпта Координатора.
 *
 * Жёсткий запрет — в `roleLimits`. Здесь — то, что в промпте иначе придётся
 * писать руками и что разъедется с кодом через неделю: какие роли сейчас
 * заняты, сколько ещё можно выдать и что произойдёт при попытке.
 *
 * Зачем вообще, если есть жёсткий запрет: отказ должен быть предсказуем.
 * Координатор, который не видит занятости, будет нарезать карточки, получать
 * отказ и тратить ходы на выяснение. Предупреждение превращает отказ в
 * известное правило.
 */
/**
 * Раскладка по квотам: чей аккаунт сейчас дешевле потратить.
 *
 * Владелец сформулировал правило так: «квота на аккаунт, а не на агента, то
 * есть если в каком-то аккаунте закончились лимиты — продолжает работу другой
 * аккаунт. Координатор или скрипт могут гибко распределять задачи между
 * аккаунтами, чтобы квота не заканчивалась никогда. На каждом аккаунте будут
 * дублироваться все роли».
 *
 * Отсюда три следствия, и все три — в коде, а не в намерениях.
 *
 *   1. **Считать надо аккаунты, а не агентов.** Тридцать три агента на четырёх
 *      аккаунтах — это четыре квоты. Ограничивать «одна работа на роль» всё
 *      равно нужно (файлы), но это не про квоту.
 *   2. **Роль привязана к аккаунту, а не к слоту.** Аккаунт может держать
 *      несколько контейнеров: тогда «свободный слот» — не единственный адрес
 *      роли, и выбирать надо среди всех слотов этого аккаунта.
 *   3. **Расход ровный.** Если всегда брать первый свободный слот, первый
 *      аккаунт выгорит за день, а остальные будут простаивать. Поэтому слот
 *      выбирается по наименьшему расходу, а не по порядку в таблице.
 *
 * Почему ровный расход, а не «максимальная загрузка»: квота восстанавливается
 * по времени, и сгоревший аккаунт — это минус четверть парка до полуночи.
 * Ровный расход держит запас, из которого можно добрать, когда один аккаунт
 * всё-таки упрётся. Это то же правило владельца «чтобы квота не заканчивалась
 * никогда», выраженное числом.
 */

/**
 * Расход по аккаунту: сколько живых выдач и какой уровень риска.
 *
 * «Риск» — не догадка: он считается из отметок лимита в журнале. Аккаунт, у
 * которого лимит уже был сегодня, получает больший вес и берётся последним:
 * повторный лимит на нём обнулит остаток и оставит парк без запаса.
 */
export function accountUsage({ slots = [], runs = [], state = new Map() } = {}) {
  const out = new Map();
  for (const slot of slots) {
    const key = norm(slot.account);
    if (!key) continue;
    if (!out.has(key)) {
      const mark = state.get(key);
      out.set(key, {
        account: slot.account,
        slots: [],
        live: 0,
        limited: Boolean(mark?.limited),
        until: mark?.until || 0,
      });
    }
    out.get(key).slots.push(slot.slotId);
  }
  for (const run of runs.filter(isLiveRun)) {
    const key = norm(run["Аккаунт"]);
    const entry = out.get(key);
    if (entry) entry.live += 1;
  }
  return out;
}

/**
 * Порядок слотов для выдачи: сначала самые «дешёвые» аккаунты.
 *
 * Сортировка устойчивая и по числам, а не по строке: одинаковый расход
 * разрешается именем слота, чтобы выдача была воспроизводимой. Иначе два
 * одинаковых запуска дают разные ответы, и тест на раскладку становится
 * невозможным.
 */
export function byAccountCost(slots = [], { runs = [], state = new Map(), admin = false } = {}) {
  const usage = accountUsage({ slots, runs, state });
  return slots
    .map((slot) => {
      const entry = usage.get(norm(slot.account)) || { live: 0, limited: false, until: 0 };
      // Лимит — не «отказ», а «последний в очереди»: он мог уже истечь, а
      // отметка в журнале осталась. Отказ делается отдельно, в slotGate.
      return { slot, live: entry.live, limited: entry.limited, until: entry.until };
    })
    .filter((entry) => Boolean(entry.slot.admin) === Boolean(admin))
    .sort((a, b) => {
      if (a.limited !== b.limited) return a.limited ? 1 : -1;
      if (a.live !== b.live) return a.live - b.live;
      return String(a.slot.slotId).localeCompare(String(b.slot.slotId));
    });
}

/**
 * Где ещё живёт эта роль.
 *
 * Нужно диспетчеру: одна роль на всех аккаунтах означает, что «занят слот» не
 * равно «роль недоступна». Без этого выдача отказывала бы при первом же занятом
 * контейнере, хотя рядом свободен другой аккаунт — и параллельность,
 * ради которой всё делалось, умирала бы на ровном месте.
 */
export function slotsForRole({ slots = [], role = "", admin = false } = {}) {
  return slots.filter((slot) => slot.enabled && Boolean(slot.admin) === Boolean(admin));
}

export function limitNotes({ roles = [], runs = [], maxPerRole = 1, maxParallel = 1 } = {}) {
  const live = runs.filter(isLiveRun);
  const byRole = new Map();
  for (const run of live) {
    const key = norm(run["Роль"]);
    if (!key) continue;
    byRole.set(key, (byRole.get(key) || 0) + 1);
  }
  const busy = [];
  const free = [];
  for (const role of roles) {
    const name = String(role?.name || "").trim();
    if (!name) continue;
    const count = byRole.get(norm(name)) || 0;
    if (count > 0) busy.push({ role: name, count });
    else free.push(name);
  }
  return {
    maxPerRole,
    maxParallel,
    busy,
    free,
    /** Человеческая строка для блока промпта: коротко и без кодов. */
    text:
      (busy.length
        ? `Заняты прямо сейчас: ${busy.map((item) => `${item.role} (${item.count})`).join(", ")}. ` +
          `Второй карточки этим ролям не будет: транспорт откажет. `
        : "Ни одна роль сейчас не занята. ") +
      (free.length ? `Свободны: ${free.join(", ")}. ` : "") +
      `Одновременно выдаётся не больше ${maxParallel}.`,
  };
}
